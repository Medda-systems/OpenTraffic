// Turns the sign-in page (src/sign-in) into Sources/OpenTrafficCore/SignInTemplate.swift: static HTML,
// its CSS, and the Geist font inlined, since the page may load nothing from elsewhere.
// Run with `npm run sign-in` after changing the page.
import { readFile, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import { styles, page, passwordField, passwordFieldInvalid, nameField } from "../dist-sign-in/render.js"

const require = createRequire(import.meta.url)
const font = await readFile(require.resolve("@fontsource-variable/geist/files/geist-latin-wght-normal.woff2"))
const fontFace = `@font-face{font-family:'Geist Variable';font-style:normal;font-display:swap;font-weight:100 900;src:url(data:font/woff2;base64,${font.toString("base64")}) format('woff2')}`

const document = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>__OT_SHARE_NAME__ · OpenTraffic</title>
<style>${fontFace}${styles}</style>
</head>
<body>${page}</body>
</html>
`

const swift = (name, value) => {
  if (value.includes('"""##')) throw new Error(`${name} can't be written as a Swift raw string`)
  return `    static let ${name} = ##"""\n${value.replace(/\n$/, "")}\n"""##\n`
}
const out = new URL("../../Sources/OpenTrafficCore/SignInTemplate.swift", import.meta.url)
await writeFile(out, `// Generated by website/scripts/build-sign-in.mjs from website/src/sign-in. Don't edit by hand.
// swiftlint:disable all

/// OpenTraffic's sign-in page, built from the website's shadcn components. \`ShareAccess\` fills in
/// the __OT_…__ values and the \`<template data-ot-slot>\` parts.
enum SignInTemplate {
${[swift("page", document), swift("passwordField", passwordField), swift("passwordFieldInvalid", passwordFieldInvalid), swift("nameField", nameField)].join("\n")}}
`)
console.log(`Wrote ${out.pathname} (${Math.round(document.length / 1024)} KB page)`)
